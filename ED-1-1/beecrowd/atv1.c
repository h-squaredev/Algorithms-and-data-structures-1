#include <stdio.h>
 
int main() {
 
    int A, B, X;
    
    // Lê o primeiro valor da entrada
    scanf("%d", &A);
    
    // Lê o segundo valor da entrada
    scanf("%d", &B);
    
    // Calcula a soma
    X = A + B;
    
    // Imprime o resultado no formato exato pedido
    printf("X = %d\n", X);
 
    return 0;
}